"""Generate readable views from the only status source. --check rejects drift."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / "docs/planning"


def render():
    raw = (PLAN / "backlog.json").read_bytes()
    plan = json.loads(raw)
    items = plan["items"]
    ids = [i["id"] for i in items]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate IDs")
    required = [
        "source",
        "priority",
        "stage",
        "user",
        "permissions",
        "behavior",
        "configuration",
        "acceptance",
        "dependencies",
        "status",
        "evidence",
        "owner",
        "estimate",
        "blockers",
        "history",
        "baseline",
        "forecast",
        "actual",
    ]
    manifest = json.loads(
        (PLAN / "references/manifest.json").read_text(encoding="utf-8")
    )
    if not set(manifest["initial_ids"]).issubset(ids):
        raise ValueError("A preserved requirement ID was deleted")
    for source in manifest["files"]:
        if (
            hashlib.sha256((ROOT / source["path"]).read_bytes()).hexdigest()
            != source["sha256"]
        ):
            raise ValueError("Frozen source changed: " + source["path"])
    mapping = {i["id"]: i for i in items}
    visiting, visited = set(), set()

    def walk(id):
        if id in visiting:
            raise ValueError("Dependency cycle: " + id)
        if id in visited:
            return
        visiting.add(id)
        for dep in mapping[id]["dependencies"]:
            if dep not in mapping:
                raise ValueError("Unknown dependency: " + dep)
            walk(dep)
        visiting.remove(id)
        visited.add(id)

    for item in items:
        if any(k not in item for k in required) or not item["acceptance"]:
            raise ValueError("Incomplete requirement: " + item["id"])
        if any(id not in mapping for id in item["related"]):
            raise ValueError("Unknown relation")
        if any(id not in mapping for id in item["covered_by"]):
            raise ValueError("Unknown coverage task")
        if item["status"] not in (
            "propuesto",
            "listo",
            "en desarrollo",
            "bloqueado",
            "en validación",
            "terminado",
            "diferido",
            "cancelado",
        ):
            raise ValueError("Unknown status")
        source_path = item["source"]["path"].split(":")[0]
        if not (ROOT / source_path).exists():
            raise ValueError("Missing source: " + source_path)
        walk(item["id"])
    for id in [f"S{n:02}" for n in range(16)]:
        if id not in mapping:
            raise ValueError("Missing epic: " + id)
    digest = hashlib.sha256(raw).hexdigest()
    header = (
        f"<!-- Generated by python scripts/planning.py; source SHA256 {digest} -->\n"
    )
    backlog = [
        header,
        "# Backlog · Medical Appointment System\n",
        "Fuente única: [backlog.json](backlog.json). Texto original íntegro y procedencia en cada requisito. No editar esta vista.\n",
    ]
    backlog += [
        "\n| ID | Solicitud | Estado | Implementación | Validación |\n|---|---|---|---|---|"
    ]
    for i in items:
        if len(i["id"]) == 3:
            backlog.append(
                f"| {i['id']} | {i['title']} | {i['status']} | {i['implementation']} | {i['validation']} |"
            )
    gantt = [
        header,
        "# Gantt y dependencias\n",
        plan["capacity"],
        plan["baseline_policy"],
        "\nFechas vacías = **sin estimar**. Horas de trabajo no son días de calendario. No hay fecha de go-live. La espera por terceros no tiene duración conocida.\n",
        "| ID | Estado | Trabajo (horas) | Línea base inicio / fin | Previsión inicio / fin | Dependencias | Bloqueo / siguiente paso |",
        "|---|---|---|---|---|---|---|",
    ]
    for i in items:
        backlog += [
            f"\n## {i['id']} · {i['title'].replace(chr(10), ' ').strip()}\n",
            f"**{i['status']}** · {i['priority']} · {i['stage']} · Responsable: {i['owner']}\n",
            f"Fuente: `{i['source']['path']}` ({i['source']['date']}). Relacionados: {', '.join(i['related']) or 'ninguno'}.\n",
            f"Tipo: {i['work_kind']}. Implementación: {i['implementation']}. Validación: {i['validation']}. Cobertura: {', '.join(i['covered_by']) or 'sin entrega asignada'}.\n",
            f"Usuario: {i['user']}\n\nPermisos: {i['permissions']}\n\nConfiguración: {i['configuration']}\n",
            i["need"],
            "\nCriterios:\n"
            + "\n".join("- " + c.replace("\n", " ") for c in i["acceptance"]),
            "\nEvidencia: "
            + ("; ".join(i["evidence"]) or "No ejecutada / sin evidencia de cierre"),
            "\nBloqueos: " + ("; ".join(i["blockers"]) or "ninguno registrado"),
            "\nSiguiente acción: " + i["next_action"],
        ]

        def dates(v):
            return (v["start"] or "sin estimar") + " / " + (v["end"] or "sin estimar")

        work = str(i["estimate"]["range"] or i["estimate"]["value"] or "sin estimar")
        gantt.append(
            f"| {i['id']} | {i['status']} | {work} | {dates(i['baseline'])} | {dates(i['forecast'])} | {', '.join(i['dependencies']) or '—'} | {('; '.join(i['blockers']) or i['next_action']).replace('|', '/')} |"
        )
    gantt += [
        "\n```mermaid",
        "gantt",
        "  title Hitos de inicio conocidos (sin compromiso de fin)",
        "  dateFormat YYYY-MM-DD",
    ]
    for schedule, label in [
        ("baseline", "Línea base"),
        ("forecast", "Previsión vigente"),
    ]:
        gantt.append("  section " + label)
        for i in items:
            if i["work_kind"] == "tarea" and i[schedule]["start"]:
                gantt.append(
                    f"  {i['id']} inicio :milestone, {schedule}_{i['id'].replace('.', '_')}, {i[schedule]['start']}, 0d"
                )
    gantt += ["```", "\n```mermaid", "flowchart LR"]
    for i in items:
        if len(i["id"]) == 3 or (
            i["id"].startswith(("S00.", "S01."))
            and ".R" not in i["id"]
            and ".AC-" not in i["id"]
        ):
            gantt.append(f'  {i["id"].replace(".", "_")}["{i["id"]} · {i["status"]}"]')
        for d in i["dependencies"]:
            gantt.append(f"  {d.replace('.', '_')} --> {i['id'].replace('.', '_')}")
    gantt += [
        "```",
        "\nDiagrama de precedencias complementario al calendario tabular; no se dibujan barras con duraciones inventadas.",
    ]
    return {
        "BACKLOG.md": "\n".join(backlog) + "\n",
        "GANTT.md": "\n".join(gantt) + "\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in render().items():
        path = PLAN / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Outdated view: " + name)
        else:
            path.write_text(content, encoding="utf-8")
    print("Planning IDs, dependencies, criteria and generated views: OK")
